**ملخص الميزة:**  
بطاقة ولاء تُمنح لكل حساب، حيث يُحصل على قهوة عاشرة مجانية لكل مشروب ساخن مدفوع.

---

**القواعد:**  
- لا تُحسب إلا المشروبات الساخنة المدفوعة، بأي حجم.  
- الطوابع لا تنتهي صلاحيتها.  
- بطاقة واحدة لكل حساب.  
- المشروب المسترد يُلغي طابعه.  
- المشروب المجاني هو أي مشروب ساخن حتى سعر اللاتيه الكبير.  
- الفرانع يتشاركان البطاقة.

---

**معايير قبول (Given / When / Then):**

Given: العميل يشتري مشروبًا ساخنًا مُدفوعًا،  
When: المشروب يُحسب كطابع،  
Then: يُضاف طابع إلى البطاقة.

Given: العميل يشتري مشروبًا ساخنًا مُستردًا،  
When: يتم استرداد المشروب،  
Then: يُلغي طابع المشروب المُشتري.

Given: العميل يمتلك بطاقة ولاء،  
