**ماذا يفعل هذا "الحساب"؟**

تخيل أنك مدير مقهى، وتحتاج إلى حساب **مبلغ مُجمّع من مبيعات** لبعض الأصناف (مثل الكافيه، الشاي، أو المكرونة).

هذا "الحساب" (الذي يُسمى `calc`) يُحسب المبلغ الكلي من المبيعات، وفقًا لقواعد بسيطة:

1. **يُحسب المبلغ من كل بند مبيعات**  
   - كل بند (مثل "كوب شاي" أو "كوب قهوة") له:
     - **السعر** (مثلاً 10 ريال)
     - **الكمية** (مثلاً 5 كوب)
   - يضرب السعر في الكمية، ويجمع كل هذه القيم لينتج مبلغ إجمالي.

2. **إذا كان هناك "مبلغ كبير" (أكبر من 20000 ريال)**  
   - يُقلّ من المبلغ 10% (مثلاً لو كان 25000، يُقلّ 2500، يصبح 22500)

3. **إذا كان العميل "مميز" (VIP)**  
   - يُقلّ من المبلغ 500 ريال كمكافأة أو خصم خاص.

4. **إذا كان المبلغ الناتج سالبًا** (أي أن الخصم تجاوز المبيعات)  
   - يُعاد إلى 0 (أي لا يُسمح أن يكون سالبًا).

