الملفات تُستخدم في مشروع لتحليل أو تقارير أوامر، حيث:

- `legacy/data/orders.json` يحتوي على بيانات أوامر (مثلاً: معلومات عن العملاء، كميات، أسعار).  
- `legacy/index.js` هو الملف الذي يبدأ التشغيل، ويُحمّل البيانات من الملف، ثم يُنتج تقريرًا باستخدام `report.make()`.  
- `legacy/lib/store.js` يُقرأ الملف وينتج بيانات مُحلّلة.  
- `legacy/lib/calc.js` يُحسب المبلغ الإجمالي لكل أمر (باستخدام كمية وسعر)، مع خصم إذا كان العميل VIP أو إذا تجاوز المبلغ 20000.  
- `legacy/lib/report.js` يُنتج تقريرًا يُظهر كل أمر مع مبلغه، ثم يُظهر المجموع النهائي.

**ما يفعله كل ملف (بشكل مختصر):**  
- `legacy/data/orders.json`: يحتوي على بيانات أوامر (مثلاً: ID، نوع العميل، قائمة المنتجات).  
- `legacy/index.js`: يُحمّل البيانات ويُنتج تقريرًا مُفصّلًا.  
- `legacy/lib/calc.js`: يحسب المبلغ الإجمالي لكل أمر مع خصومات.  
- `legacy/lib/report.js`: يُنتج تقريرًا من البيانات المُحسبَة.  
- `legacy/lib/store.js`: يُقرأ ملف البيانات من المجلد.  

**أي ملف يعمل أولاً؟**  
`legacy/index.js` يعمل أولاً لأنه يُبدأ التشغيل ويُحمّل البيانات.
