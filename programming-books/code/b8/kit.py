"""Book 8's examples are JavaScript (Node 22) that call the Claude API through the official SDK,
@anthropic-ai/sdk. They run against the book's practice server (practice/server.mjs), a local stand-in that
speaks the API's format and answers from each chapter's practice.json: no account, no key, no cost. The
practice server's answers are written for the book, not generated by Claude, and the book says so wherever
it shows one. Pointing the same code at the real API needs only a key and the default address.

This kit writes a chapter's files in each language, starts the practice server in the project, runs each
command as a reader would, in a project outside the repository, and records each terminal session.
"""
import os
import re
import shutil
import socket
import subprocess
import time
import importlib.util
from pathlib import Path

_spec = importlib.util.spec_from_file_location("b5kit", Path(__file__).parent.parent / "b5" / "kit.py")
b5kit = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(b5kit)
HOME, Session, fill, write = b5kit.HOME, b5kit.Session, b5kit.fill, b5kit.write

HERE = Path(__file__).parent
WORK = HOME / "b8-work"
SDK = "@anthropic-ai/sdk@1.8.0"
PORT = 4141
_env = b5kit.env


def env():
    e = _env()
    e["PATH"] = "/opt/node22/bin:" + e["PATH"]
    # The SDK reads these two variables: the practice server's address, and its key.
    e["ANTHROPIC_BASE_URL"] = f"http://127.0.0.1:{PORT}"
    e["ANTHROPIC_API_KEY"] = "test-key"
    # The browser for chapters that test an artifact, already installed on this machine.
    for k in ("PLAYWRIGHT_BROWSERS_PATH", "PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD"):
        if os.environ.get(k):
            e[k] = os.environ[k]
    return e


b5kit.env = env

WIDTH = 74


def wrap_comments(text):
    """A comment line longer than the printed page is folded into several, so the book never wraps code."""
    out = []
    for line in text.split("\n"):
        m = re.match(r"^(\s*// )(.*)$", line)
        if not m or len(line) <= WIDTH:
            out.append(line)
            continue
        prefix, rest = m.groups()
        current = ""
        for word in rest.split(" "):
            if current and len(prefix) + len(current) + 1 + len(word) > WIDTH:
                out.append(prefix + current)
                current = word
            else:
                current = f"{current} {word}" if current else word
        out.append(prefix + current)
    return "\n".join(out)


def deps(extra=()):
    """The SDK (and any extra packages), installed once for every chapter's project. Playwright is linked
    from this machine's global install, whose browser is already there; a reader runs
    `npm install playwright` and `npx playwright install chromium` instead."""
    base = WORK / "_deps"
    link = "playwright" in extra
    extra = [x for x in extra if x != "playwright"]
    wanted = [SDK, *extra]
    stamp = base / "installed.txt"
    if not stamp.exists() or stamp.read_text().split() != wanted:
        base.mkdir(parents=True, exist_ok=True)
        write(base, {"package.json": '{"type": "module", "private": true}\n'})
        subprocess.run(["chown", "-R", "reader:reader", str(WORK)], check=False)
        out, code = b5kit.sh("npm install --silent " + " ".join(wanted), base, timeout=1800)
        if code:
            raise RuntimeError(out)
        stamp.write_text(" ".join(wanted))
    target = base / "node_modules" / "playwright"
    if link and not target.exists():
        target.symlink_to(Path("/opt/node22/lib/node_modules/playwright"))
    return base / "node_modules"


class Practice:
    """The practice server, started in a project folder for the time of a chapter's runs."""

    def __init__(self, base):
        cmd = ["node", "practice/server.mjs"]
        if b5kit.AS_READER:
            cmd = [b5kit.RUNUSER, "-u", "reader", "--"] + cmd
        self.proc = subprocess.Popen(cmd, cwd=base, env=env(), stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        for _ in range(100):
            try:
                socket.create_connection(("127.0.0.1", PORT), timeout=0.2).close()
                return
            except OSError:
                time.sleep(0.1)
        raise RuntimeError("the practice server did not start")

    def stop(self):
        self.proc.terminate()
        self.proc.wait(timeout=10)


def chapter(here, words_by_lang, files, runs, extra=(), binaries=None):
    """files: {path: text} with {w_...} words, practice.json among them; runs: [(transcript, command[, keep])];
    binaries(lang) -> {path: bytes} for the images and documents a chapter sends.
    Every run of a chapter talks to one practice server, started fresh, so the runs are reproducible."""
    modules = deps(extra)
    only = os.environ.get("B8_LANG")  # B8_LANG=ar runs one edition
    for lang, words in words_by_lang.items():
        if only and lang != only:
            continue
        out = here / lang
        shutil.rmtree(out, ignore_errors=True)
        base = WORK / here.name / lang
        shutil.rmtree(base, ignore_errors=True)
        base.mkdir(parents=True)
        (base / "node_modules").symlink_to(modules)
        texts = {"package.json": '{"type": "module", "private": true}\n'}
        texts.update({name: wrap_comments(fill(text, words)) for name, text in files.items()})
        write(base, texts)
        write(out, texts)
        for name, data in (binaries(lang) if binaries else {}).items():  # images, PDFs: made by the chapter
            for folder in (base, out):
                (folder / name).parent.mkdir(parents=True, exist_ok=True)
                (folder / name).write_bytes(data)
        (base / "practice").mkdir(exist_ok=True)
        shutil.copyfile(HERE / "practice" / "server.mjs", base / "practice" / "server.mjs")
        subprocess.run(["chown", "-R", "reader:reader", str(base)], check=False)
        server = Practice(base)
        try:
            for transcript, command, *keep in runs:
                s = Session(base)
                s.run(fill(command, words), keep=keep[0] if keep else None, check=False)
                s.save(out / transcript)
        finally:
            server.stop()
        if (base / "artifacts").is_dir():  # what the examples made, kept with the book's code
            shutil.copytree(base / "artifacts", out / "artifacts")
        print("wrote", out)
