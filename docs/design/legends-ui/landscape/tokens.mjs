// [Sprint 55] The drafts' colours and sizes from the one source (docs/design/tokens.json), as the web's generator does.
// Run from the repository root after any change in tokens.json: node docs/design/legends-ui/landscape/tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const t = JSON.parse(readFileSync(join(here, '../../tokens.json'), 'utf8'))
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())
const vars = (o, p) => Object.entries(o).filter(([k]) => !k.startsWith('$')).map(([k, v]) => `  --${p}-${kebab(k)}: ${v};`)
const out = [
  '/* Generated by tokens.mjs from docs/design/tokens.json. Do not edit. */',
  ':root {',
  ...vars(t.color, 'color'),
  ...vars(t.broadcast, 'color-broadcast'),
  ...Object.entries(t.type).filter(([k]) => !k.startsWith('$')).flatMap(([k, v]) => [`  --text-${kebab(k)}: ${v.size}px;`, `  --text-${kebab(k)}-lh: ${v.line};`, `  --text-${kebab(k)}-w: ${v.weight};`]),
  ...vars(Object.fromEntries(Object.entries(t.spacing).map(([k, v]) => [k, `${v}px`])), 'space'),
  ...vars(Object.fromEntries(Object.entries(t.size.radius).map(([k, v]) => [k, `${v}px`])), 'radius'),
  ...Object.entries(t.line).filter(([k]) => !k.startsWith('$')).flatMap(([k, v]) => [`  --line-${k}: ${v.bg};`, `  --line-${k}-fg: ${v.fg};`]),
  `  --touch: ${t.touch.web}px;`,
  '}',
  '.day {',
  ...vars(t.colorLight, 'color'),
  '}',
  '',
]
writeFileSync(join(here, 'tokens.css'), out.join('\n'))
console.log('drafts tokens written')
