// [Sprint 09 G1] The director's golden vectors, shared with Unity (docs/api/director-golden.json): the cartoon's own pure
// modules (plan.ts with director.ts and timing.ts, and clock.ts) run over every minute of the sample match (with the
// server's story) and over a story for every scene it lacks, at every tier. The web test (plan.test.ts) checks the
// cartoon still gives them, and Unity's DirectorTests that its port (Shots/MinutePlan.cs) does too.
//
//   node scripts/director-golden.mjs          writes the vectors (after a change in plan.ts, director.ts, timing.ts or
//                                             clock.ts, with its port in Unity, in the same PR)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { cases } from '../src/match/feed/golden.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const sample = JSON.parse(readFileSync(resolve(root, 'docs/api/samples/liverpool-arsenal-48213.json'), 'utf8'))
const out = {
  note: 'Generated by web/scripts/director-golden.mjs from the cartoon (plan.ts, director.ts, timing.ts, clock.ts). Do not edit.',
  cases: cases(sample),
}
// one case a line: small, and a change shows as the cases it touches
const text = `{"note": ${JSON.stringify(out.note)},\n"cases": [\n${out.cases.map((c) => JSON.stringify(c)).join(',\n')}\n]}\n`
writeFileSync(resolve(root, 'docs/api/director-golden.json'), text)
console.log(`director-golden: ${out.cases.length} cases`)
