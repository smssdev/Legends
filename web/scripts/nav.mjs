// [Sprint 60 F1] The frame's sections from docs/design/nav.json, the one source for the site and the app (the app's
// is mobile/tool/nav.dart). Writes src/layouts/dock.g.ts; a page the site does not have (web: null) is left out.
// The English of each name must be the one en.ts gives it, so the two platforms say the same in both languages.
import fs from 'node:fs';

const nav = JSON.parse(fs.readFileSync(new URL('../../docs/design/nav.json', import.meta.url), 'utf8'));
const en = fs.readFileSync(new URL('../src/i18n/en.ts', import.meta.url), 'utf8');
const out = new URL('../src/layouts/dock.g.ts', import.meta.url);

const wrong = [];
const check = (ar, english) => {
  const m = en.match(new RegExp(`'${ar}': *'([^']*)'`));
  if (!m) wrong.push(`${ar}: no English in en.ts (nav.json says ${english})`);
  else if (m[1] !== english) wrong.push(`${ar}: en.ts says «${m[1]}», nav.json «${english}»`);
};
const page = (k) => {
  const p = nav.pages[k];
  if (!p) throw new Error(`nav.json: no page ${k}`);
  return p;
};
for (const s of nav.dock) check(s.ar, s.en);
check(nav.more.ar, nav.more.en);
for (const p of Object.values(nav.pages)) if (p.web !== null) check(p.ar, p.en);
if (wrong.length) {
  console.error(`nav: the names differ from en.ts:\n  ${wrong.join('\n  ')}`);
  process.exit(1);
}

const q = (v) => JSON.stringify(v);
const dock = nav.dock.map((s) => {
  const items = s.items.filter((k) => page(k).web !== null).map((k) => page(k).web);
  return `  { key: ${q(s.key)}, label: ${q(s.ar)}, icon: ${q(s.icon)}, color: ${q(s.color)}, ink: ${q(s.ink)}, items: ${q(items)} },`;
});
const inSlot = nav.more.in_slot.filter((k) => page(k).web !== null).map((k) => page(k).web);
const always = nav.more.always.filter((k) => page(k).web !== null)
  .map((k) => `  { path: ${q(page(k).web)}, label: ${q(page(k).ar)}, icon: ${q(page(k).icon.web)} },`);
const labels = Object.entries(nav.pages).filter(([, p]) => p.web !== null && !p.web.startsWith('/'))
  .map(([, p]) => `  ${q(p.web)}: ${q(p.ar)},`);

const text = `// GENERATED by scripts/nav.mjs from docs/design/nav.json: do not edit (npm run nav).
import type { PATHS } from '../components/Icon.vue'

export type DockKey = ${nav.dock.map((s) => q(s.key)).join(' | ')}
/** [Sprint 63 G4] Each section's tile: its colour (a token: var(--color-<color>)) and its icon's ink on it. */
export interface DockSection { key: DockKey; label: string; icon: keyof typeof PATHS; color: string; ink: 'dark' | 'light'; items: string[] }
/** The six sections: each a list of SECTIONS names, the first where a tap on the section goes. */
export const DOCK: DockSection[] = [
${dock.join('\n')}
]
/** «${nav.more.ar}» inside a slot: the league's pages (by SECTIONS name). */
export const MORE_IN_SLOT = ${q(inSlot)}
/** «${nav.more.ar}» for everyone: the community, the shop, the account. */
export const MORE_ALWAYS: { path: string; label: string; icon: keyof typeof PATHS }[] = [
${always.join('\n')}
]
export const MORE_LABEL = ${q(nav.more.ar)}
/** Each page's one name (by SECTIONS name), the app's too. */
export const PAGE_LABELS: Record<string, string> = {
${labels.join('\n')}
}
`;
fs.writeFileSync(out, text);
console.log(`nav: ${nav.dock.length} sections → src/layouts/dock.g.ts`);
