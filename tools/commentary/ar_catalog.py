def story_lines():
    rows = []
    with open(os.path.join(RAW, 'ar', 'story', 'files.txt'), encoding='utf-8') as f:
        for line in f:
            if line.startswith('#') or not line.strip():
                continue
            name, tone, text = line.rstrip('\n').split('\t')
            rows.append((name, tone, text))
    return rows


