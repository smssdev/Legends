"""[Sprint 63 G3] The game's one icon set: each icon a file of brand/icons (a 24 grid, a 1.75 stroke in the text's
colour, round ends, one path), read here into the site's map and the app's, so both draw the same icon from the same
drawing. Change or add a file, then run:

    python3 tools/brand/icons.py      # web/src/components/icons.g.ts and mobile/lib/ui/widgets/glm_icons.g.dart
"""

import pathlib
import re
import shutil
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / 'brand' / 'icons'
WEB = ROOT / 'web' / 'src' / 'components' / 'icons.g.ts'
APP = ROOT / 'mobile' / 'lib' / 'ui' / 'widgets' / 'glm_icons.g.dart'
STROKE = '1.75'

icons = {}
for f in sorted(SRC.glob('*.svg')):
    text = f.read_text()
    paths = re.findall(r'<path d="([^"]+)"', text)
    if len(paths) != 1 or not re.fullmatch(r'[a-z][a-z0-9_]*', f.stem):
        raise SystemExit(f'icons: {f.name} must be one <path d="…"> and a lowercase name')
    icons[f.stem] = paths[0]


def camel(name):
    head, *rest = name.split('_')
    return head + ''.join(w.title() for w in rest)


WEB.write_text(
    '// Generated by tools/brand/icons.py from brand/icons/*.svg: do not edit (Sprint 63 G3).\n'
    f'export const STROKE = {STROKE}\n'
    'export const PATHS = {\n' + ''.join(f"  {n}: '{d}',\n" for n, d in icons.items()) + '} as const\n'
)
APP.write_text(
    '// Generated by tools/brand/icons.py from brand/icons/*.svg: do not edit (Sprint 63 G3).\n'
    '// ignore_for_file: constant_identifier_names\n\n'
    '/// The game\'s line icons, the site\'s same drawings (web/src/components/icons.g.ts).\n'
    'enum GlmIcons {\n' + ''.join(f"  {camel(n)}('{d}'),\n" for n, d in icons.items()) + ';\n\n'
    '  const GlmIcons(this.path);\n\n  final String path;\n}\n\n'
    f'const glmIconStroke = {STROKE};\n'
)
# The app's file as `dart format -l 140` would write it (its check rejects anything else).
if shutil.which('dart'):
    subprocess.run(['dart', 'format', '-l', '140', str(APP)], check=False, capture_output=True)
print(f'icons: {len(icons)} → {WEB.relative_to(ROOT)}, {APP.relative_to(ROOT)}')
