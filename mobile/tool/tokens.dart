// [Sprint 15 F1] The design tokens for the app, from the one source the web uses (docs/design/tokens.json): the colours of
// both looks (night and day), the accents' darker ink by day, the lines, the fitness and rating colours, and the sizes.
// Run after any change in tokens.json: `dart run tool/tokens.dart` (CI checks the file is current).
import 'dart:convert';
import 'dart:io';
import 'dart:math' as math;

String hex(Object? h) => '0xFF${(h as String).substring(1).toUpperCase()}';

/// One field of a JSON object.
Object? at(Object? m, String k) => (m as Map<dynamic, dynamic>)[k];
String ident(String s) => s.replaceAllMapped(RegExp(r'[^A-Za-z0-9]+(.)'), (m) => m[1]!.toUpperCase());

/// [Sprint 65 F4] The relative luminance of #RRGGBB (WCAG 2).
double luminance(String hex) {
  double ch(int i) {
    final x = int.parse(hex.substring(i, i + 2), radix: 16) / 255;
    return x <= 0.03928 ? x / 12.92 : math.pow((x + 0.055) / 1.055, 2.4).toDouble();
  }

  return 0.2126 * ch(1) + 0.7152 * ch(3) + 0.0722 * ch(5);
}

double ratio(String a, String b) {
  final x = luminance(a), y = luminance(b);
  return (math.max(x, y) + 0.05) / (math.min(x, y) + 0.05);
}

/// [Sprint 65 F4] Every pair in tokens.json contrast, at night and by day, as web/scripts/tokens.mjs checks it: what falls short.
List<String> contrastShort(Map<String, dynamic> t, Map<String, dynamic> night, Map<String, dynamic> day, Map<String, dynamic> ink) {
  final c = t['contrast'] as Map<String, dynamic>;
  final grounds = (c['grounds'] as List<dynamic>).cast<String>();
  final lines = t['line'] as Map<String, dynamic>;
  final short = <String>[];
  for (final look in ['night', 'day']) {
    final pal = look == 'day' ? day : night;
    String pick(String n) => n.startsWith('ink:')
        ? (look == 'day' ? (ink[n.substring(4)] ?? pal[n.substring(4)]) : pal[n.substring(4)]) as String
        : (pal[n] ?? n) as String;
    void check(String fg, String bg, num min, String what) {
      final r = ratio(fg, bg);
      if (r < min) short.add('$look: $what ${r.toStringAsFixed(2)} < $min');
    }

    for (final kind in ['text', 'marks']) {
      final k = c[kind] as Map<String, dynamic>;
      for (final fg in (k['fg'] as List<dynamic>).cast<String>()) {
        for (final g in grounds) {
          check(pick(fg), pal[g] as String, k['min'] as num, '$fg on $g');
        }
      }
    }
    final fills = c['fills'] as Map<String, dynamic>;
    for (final pair in (fills['pairs'] as List<dynamic>).cast<List<dynamic>>()) {
      final fg = pair[0] as String;
      if (fg.startsWith('line:')) {
        final l = lines[fg.substring(5)] as Map<String, dynamic>;
        check(l['fg'] as String, l['bg'] as String, fills['min'] as num, '$fg badge');
      } else {
        check(pick(fg), pick(pair[1] as String), fills['min'] as num, '$fg on ${pair[1]}');
      }
    }
  }
  return short;
}

void main() {
  final t = jsonDecode(File('../docs/design/tokens.json').readAsStringSync()) as Map<String, dynamic>;
  // [X114] The app's night is the web's with tokens.json app.color over it (softer on the eyes); the web never reads it.
  final app = (t['app'] as Map<String, dynamic>?) ?? const <String, dynamic>{};
  final night = {
    ...Map<String, dynamic>.from(t['color'] as Map<dynamic, dynamic>),
    ...Map<String, dynamic>.from((app['color'] as Map<dynamic, dynamic>?) ?? const {}),
  };
  final day = {
    ...Map<String, dynamic>.from(t['color'] as Map<dynamic, dynamic>),
    ...Map<String, dynamic>.from(t['colorLight'] as Map<dynamic, dynamic>)..remove(r'$comment'),
  };
  final ink = Map<String, dynamic>.from(t['ink'] as Map<dynamic, dynamic>)..remove(r'$comment');
  final short = contrastShort(t, night, day, ink);
  if (short.isNotEmpty) {
    stderr.writeln('tokens: ${short.length} colour pair(s) under their contrast\n  ${short.join('\n  ')}');
    exit(1);
  }
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/tokens.dart from docs/design/tokens.json. Do not edit by hand.')
    ..writeln('// ignore_for_file: constant_identifier_names')
    ..writeln("import 'package:flutter/animation.dart';")
    ..writeln()
    ..writeln('/// The colours of one look (night or day), as the web\'s CSS variables.')
    ..writeln('class GlmPalette {')
    ..writeln('  const GlmPalette({${night.keys.map((k) => 'required this.${ident(k)}').join(', ')}});');
  for (final k in night.keys) {
    b.writeln('  final Color ${ident(k)};');
  }
  b
    ..writeln('}')
    ..writeln();
  void palette(String name, Map<String, dynamic> c) {
    b.writeln('const $name = GlmPalette(');
    for (final k in night.keys) {
      b.writeln('  ${ident(k)}: Color(${hex(c[k] as String)}),');
    }
    b.writeln(');');
  }

  palette('glmNight', night);
  palette('glmDay', day);
  b
    ..writeln()
    ..writeln('/// By day, an accent\'s text takes this darker ink (4.5:1 on paper); at night the accent itself.')
    ..writeln('abstract final class GlmInk {');
  for (final e in ink.entries) {
    b.writeln('  static const ${ident(e.key)} = Color(${hex(e.value as String)});');
  }
  b
    ..writeln('}')
    ..writeln()
    ..writeln('/// [Sprint 47] The app\'s stage in the approved design: the night ground, the navy cards, the mint accent, the pills.')
    ..writeln('abstract final class GlmStage {');
  <dynamic, dynamic>{...(t['stage'] as Map<dynamic, dynamic>), ...((app['stage'] as Map<dynamic, dynamic>?) ?? const {})}.forEach((k, v) {
    if (!(k as String).startsWith(r'$')) b.writeln('  static const ${ident(k)} = Color(${hex(v as String)});');
  });
  b
    ..writeln('}')
    ..writeln()
    ..writeln('/// A player\'s line: its badge colour and text.')
    ..writeln('abstract final class GlmLine {');
  (t['line'] as Map<dynamic, dynamic>).forEach(
    (k, v) => b.writeln('  static const $k = (bg: Color(${hex(at(v, 'bg'))}), fg: Color(${hex(at(v, 'fg'))}));'),
  );
  b
    ..writeln('}')
    ..writeln()
    ..writeln('/// Fitness from its value (min, colour), highest first.')
    ..writeln('const glmFitness = [');
  (t['fitness'] as Map<dynamic, dynamic>).forEach((k, v) => b.writeln('  (min: ${at(v, 'min')}, color: Color(${hex(at(v, 'color'))})),'));
  b
    ..writeln('];')
    ..writeln()
    ..writeln('/// A match rating from its value (min, background, text), highest first.')
    ..writeln('const glmRating = [');
  for (final r in t['rating'] as List<dynamic>) {
    b.writeln('  (min: ${at(r, 'min')}, bg: Color(${hex(at(r, 'bg'))}), fg: Color(${hex(at(r, 'fg'))})),');
  }
  final size = t['size'] as Map<dynamic, dynamic>;
  b
    ..writeln('];')
    ..writeln()
    ..writeln('/// The sizes: the smallest touch target, the radii and the spacing scale.')
    ..writeln('abstract final class GlmSize {')
    ..writeln('  static const double touchMin = ${size['touchMin']};');
  (size['radius'] as Map<dynamic, dynamic>).forEach(
    (k, v) => b.writeln('  static const double radius${(k as String)[0].toUpperCase()}${k.substring(1)} = $v;'),
  );
  b
    ..writeln('  static const space = <double>[${(size['space'] as List<dynamic>).join(', ')}];')
    ..writeln('}');

  // [Sprint 54 F1] The type roles, the spacing, the touch sizes, the shadows, the motion and the broadcast palette, the
  // same names as the web's (text-caption … text-display, --space-*, --shadow-*, --ease-*, --duration-*).
  Map<String, dynamic> part(String k) =>
      Map<String, dynamic>.from(t[k] as Map<dynamic, dynamic>)..removeWhere((k, _) => k.startsWith(r'$'));
  b
    ..writeln()
    ..writeln('/// One type role: its size, line height (a multiple) and weight.')
    ..writeln('typedef GlmTypeRole = ({double size, double height, int weight});')
    ..writeln()
    ..writeln('/// The type scale: six roles (and the large display), as the web\'s text-caption … text-display.')
    ..writeln('abstract final class GlmType {');
  part('type').forEach(
    (k, v) => b.writeln('  static const GlmTypeRole $k = (size: ${at(v, 'size')}, height: ${at(v, 'line')}, weight: ${at(v, 'weight')});'),
  );
  b
    ..writeln('}')
    ..writeln()
    ..writeln('/// The spacing scale, as the web\'s --space-*.')
    ..writeln('abstract final class GlmSpace {');
  part('spacing').forEach((k, v) => b.writeln('  static const double $k = $v;'));
  b
    ..writeln('}')
    ..writeln()
    ..writeln('/// The smallest touch target: 44 on the web, 48 in the app (Material).')
    ..writeln('abstract final class GlmTouch {');
  part('touch').forEach((k, v) => b.writeln('  static const double $k = $v;'));
  b
    ..writeln('}')
    ..writeln()
    ..writeln('/// The radii, as the web\'s rounded-* (one source with GlmSize).')
    ..writeln('abstract final class GlmRadius {');
  (size['radius'] as Map<dynamic, dynamic>).forEach((k, v) => b.writeln('  static const double $k = $v;'));
  b
    ..writeln('}')
    ..writeln()
    ..writeln('/// The shadows (offset y, blur, spread, the shade\'s opacity), as the web\'s --shadow-*.')
    ..writeln('abstract final class GlmShadow {');
  part('shadow').forEach(
    (k, v) => b.writeln(
      '  static const $k = (y: ${at(v, 'y')}.0, blur: ${at(v, 'blur')}.0, spread: ${at(v, 'spread')}.0, alpha: ${at(v, 'alpha')});',
    ),
  );
  b
    ..writeln('}')
    ..writeln()
    ..writeln('/// The motion: two curves and three durations, as the web\'s --ease-* and --duration-*.')
    ..writeln('abstract final class GlmMotion {');
  part('motion').forEach((k, v) {
    if (v is List<dynamic>) {
      b.writeln('  static const $k = Cubic(${v.join(', ')});');
    } else {
      b.writeln('  static const $k = Duration(milliseconds: $v);');
    }
  });
  b
    ..writeln('}')
    ..writeln()
    ..writeln('/// The match\'s TV look (the studio, the score bug, the cards), as the web\'s --color-broadcast-*.')
    ..writeln('abstract final class GlmBroadcast {');
  part('broadcast').forEach((k, v) => b.writeln('  static const ${ident(k)} = Color(${hex(v as String)});'));
  b.writeln('}');
  File('lib/ui/tokens.g.dart').writeAsStringSync(b.toString());
  stdout.writeln('tokens: ${night.length} colours × 2 looks');
}
