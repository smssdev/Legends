// [Sprint 60 F1] The frame's sections for the app, from the one source the site uses (docs/design/nav.json; the site's
// is web/scripts/nav.mjs): the six sections and «More», each page by its one name in Arabic and English and its path
// here. A page the app does not have (app: null) is left out. Into lib/l10n/ (the names are words, and words live
// there). Run after any change in nav.json: `dart run tool/nav.dart` (CI checks the file is current).
import 'dart:convert';
import 'dart:io';

String q(Object? s) => "'${'$s'.replaceAll("'", r"\'")}'";

void main() {
  final nav = jsonDecode(File('../docs/design/nav.json').readAsStringSync()) as Map<String, dynamic>;
  final pages = (nav['pages'] as Map<String, dynamic>).cast<String, Map<String, dynamic>>();
  Map<String, dynamic> page(String k) => pages[k] ?? (throw StateError('nav.json: no page $k'));
  final keys = <String>[
    for (final s in (nav['dock'] as List<dynamic>).cast<Map<String, dynamic>>()) ...(s['items'] as List<dynamic>).cast<String>(),
    ...(((nav['more'] as Map<String, dynamic>)['in_slot']) as List<dynamic>).cast<String>(),
    ...(((nav['more'] as Map<String, dynamic>)['always']) as List<dynamic>).cast<String>(),
  ];
  String entry(String k) {
    final p = page(k);
    return "NavPage(${q(k)}, ar: ${q(p['ar'])}, en: ${q(p['en'])}, path: ${q(p['app'])}, glyph: ${q((p['icon'] as Map<String, dynamic>)['app'])}, icon: ${q((p['icon'] as Map<String, dynamic>)['web'])})";
  }

  List<String> present(List<dynamic> ks) => [
    for (final k in ks.cast<String>())
      if (page(k)['app'] != null) k,
  ];
  final more = nav['more'] as Map<String, dynamic>;
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/nav.dart from docs/design/nav.json: do not edit (dart run tool/nav.dart).')
    ..writeln()
    ..writeln('/// One page of the frame: its one name (the site\'s too), its path ({league} is the club\'s league; a path')
    ..writeln('/// without it opens over the club), its glyph (a GameGlyph name) and its line icon (brand/icons, the site\'s).')
    ..writeln('class NavPage {')
    ..writeln(
      '  const NavPage(this.key, {required this.ar, required this.en, required this.path, required this.glyph, required this.icon});',
    )
    ..writeln()
    ..writeln('  final String key, ar, en, path, glyph, icon;')
    ..writeln()
    ..writeln('  String label(String locale) => locale == \'ar\' ? ar : en;')
    ..writeln("  String route(int league) => path.replaceAll('{league}', '\$league');")
    ..writeln("  bool get push => !path.contains('{league}');")
    ..writeln('}')
    ..writeln()
    ..writeln('/// One section of the dock: its one name and its pages, the first where a tap goes.')
    ..writeln('class NavSection {')
    ..writeln('  const NavSection(this.key, {required this.ar, required this.en, required this.pages, this.icon = \'more\'});')
    ..writeln()
    ..writeln('  final String key, ar, en, icon;')
    ..writeln('  final List<NavPage> pages;')
    ..writeln()
    ..writeln('  String label(String locale) => locale == \'ar\' ? ar : en;')
    ..writeln('}')
    ..writeln()
    ..writeln('/// The six sections of the approved draft, and «More» (the league\'s pages, then everyone\'s).')
    ..writeln('const navDock = <NavSection>[');
  for (final s in (nav['dock'] as List<dynamic>).cast<Map<String, dynamic>>()) {
    b.writeln("  NavSection(${q(s['key'])}, ar: ${q(s['ar'])}, en: ${q(s['en'])}, icon: ${q(s['icon'])}, pages: [");
    for (final k in present(s['items'] as List<dynamic>)) {
      b.writeln('    ${entry(k)},');
    }
    b.writeln('  ]),');
  }
  b
    ..writeln('];')
    ..writeln("const navMore = NavSection('more', ar: ${q(more['ar'])}, en: ${q(more['en'])}, pages: [");
  for (final k in [...present(more['in_slot'] as List<dynamic>), ...present(more['always'] as List<dynamic>)]) {
    b.writeln('  ${entry(k)},');
  }
  b.writeln(']);');
  assert(keys.isNotEmpty);
  File('lib/l10n/nav.g.dart').writeAsStringSync(b.toString());
  Process.runSync('dart', ['format', '-l', '140', 'lib/l10n/nav.g.dart']);
  stdout.writeln('nav: ${(nav['dock'] as List<dynamic>).length} sections → lib/l10n/nav.g.dart');
}
